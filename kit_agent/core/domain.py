"""Domain loading.

A domain = domains/<name>/
    domain.yaml     hand-written: persona, mission, routing, hand-described tables
    team.yaml       hand-written: the multi-agent team (optional)
    generated.yaml  written by the `kit` CLI: auto-described tables, trained models, vector search
Files are merged at load time so the CLI never rewrites your hand-edited YAML.
When deployed, `kit deploy` bakes everything into kit_agent/_frozen_domain.yaml.
"""
import os
from pathlib import Path

import yaml

KIT_ROOT = Path(__file__).resolve().parents[2]
FROZEN = Path(__file__).resolve().parents[1] / "_frozen_domain.yaml"


def domain_file() -> Path:
    p = Path(os.environ.get("DOMAIN_FILE", "domains/food_equity/domain.yaml"))
    return p if p.is_absolute() else KIT_ROOT / p


def deep_merge(base: dict, over: dict) -> dict:
    out = dict(base or {})
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def _read(p: Path) -> dict:
    return (yaml.safe_load(p.read_text(encoding="utf-8")) or {}) if p.exists() else {}


def load_domain(path=None) -> dict:
    if path is None and FROZEN.exists():
        return _read(FROZEN)
    p = Path(path) if path else domain_file()
    d = _read(p)
    d = deep_merge(d, _read(p.with_name("generated.yaml")))
    team = _read(p.with_name("team.yaml"))
    if team:
        d["team"] = team.get("team", team)
    d["_dir"] = str(p.parent)
    d.setdefault("_dataset", os.environ.get("BQ_DATASET", ""))
    return d


def save_overlay(patch: dict, path=None) -> Path:
    """Deep-merge `patch` into generated.yaml next to the active domain.yaml."""
    p = Path(path) if path else domain_file()
    gen = p.with_name("generated.yaml")
    merged = deep_merge(_read(gen), patch)
    header = "# AUTO-GENERATED by the kit CLI (add-data / sql / model / embed). Safe to edit; domain.yaml wins on nothing — this file wins on conflicts.\n"
    gen.write_text(header + yaml.safe_dump(merged, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return gen


def models_of(domain: dict) -> dict:
    """All trained/declared models: new-style `models:` plus legacy single `bqml:`."""
    out = dict(domain.get("models") or {})
    legacy = domain.get("bqml") or {}
    if legacy.get("predict_sql") and "SELECT 1 AS placeholder" not in legacy["predict_sql"]:
        out.setdefault("default", {"type": "legacy", "predict_sql": legacy["predict_sql"],
                                   "instructions": legacy.get("instructions", "")})
    return out
